; ones.asm — «11» на всех индикаторах: первая программа журнала «ЮТ для умелых рук»
; (1989-02, doc/05-programmirovanie.md).
;
; Программа выводит код 11H на три пары индикаторов процессорного модуля (модуль 1),
; показывая три способа адресации: прямую (STA), косвенную через HL (MOV M,A) и
; косвенную через DE (STAX D). В журнальном листинге 13 байт и нет выхода из программы;
; здесь добавлен RST 0 — возврат в МОНИТОР (адрес 0000H), как советует примечание в
; doc/05.
;
; Конфигурация: модуль 1 (minimal), ОЗУ с C000H.
; Сборка:  make asm F=examples/asm/ones.asm          (дамп examples/asm/ones.hex)
;          asm-k580vm80a -f examples/asm/ones.asm -o ones.bin
; Запуск:  make asm-run F=examples/asm/ones.asm
; На ЮТ-88: ввести коды директивой «1» с адреса C000H, пуск — директивой «6».

DISP    EQU     9000H           ; индикаторы: 9000H — правый, 9001H — средний, 9002H — левый

        ORG     0C000H
START:  MVI     A,11H           ; занесение константы в аккумулятор (непосредственная)
        STA     DISP            ; «11» на правый индикатор (прямая адресация)
        LXI     H,DISP+1        ; адрес среднего индикатора в HL
        MOV     M,A             ; «11» на средний индикатор (косвенная через HL)
        LXI     D,DISP+2        ; адрес левого индикатора в DE
        STAX    D               ; «11» на левый индикатор (косвенная через DE)
        RST     0               ; возврат в МОНИТОР (в журнале этой команды нет)
        END     START
