; fill.asm — заполнение области памяти константой (журнал 1989-02, doc/07-programmy.md;
; готовый образ — programs/fill-const.bin, собирается из этого текста байт-в-байт).
;
; Программа просит начальный и конечный адреса области и константу, заносит константу
; во все ячейки от начального адреса до конечного включительно и выходит в МОНИТОР —
; на правом индикаторе «11». Результат смотрят директивой «5».
;
; Подпрограммы МОНИТОРА модуля 1 (monitor/monitor.asm):
;   RST 6  — ввод четырёх шестнадцатеричных цифр (адреса) в DE;
;   RST 2  — ввод двух цифр (байта) в A;
;   0259H  — сравнение HL и DE (флаг Z — равны).
;
; Конфигурация: модуль 1 (minimal).
; Сборка:  make asm F=examples/asm/fill.asm           (дамп examples/asm/fill.hex)
; Запуск:  make asm-run F=examples/asm/fill.asm, затем на клавиатуре модуля 1:
;          начальный адрес (C100), конечный адрес (C17F), константа (A5).
; На ЮТ-88: ввести коды директивой «1» с C000H, пуск — директивой «6».

CMPHD   EQU     0259H           ; подпрограмма МОНИТОРА: сравнить HL и DE

        ORG     0C000H
START:  RST     6               ; ввод начального адреса в DE
        XCHG                    ; пересылка DE в HL
        RST     6               ; ввод конечного адреса в DE
        RST     2               ; ввод константы в A
        MOV     B,A             ; пересылка константы из A в B
LOOP:   MOV     M,B             ; константа из B в ОЗУ (в журнале метка «M»,
                                ; но M — имя регистра)
        CALL    CMPHD           ; HL = DE?
        INX     H               ; HL = HL + 1 (флаги не меняет)
        JNZ     LOOP            ; если HL ≠ DE, повторить
        RST     0               ; выход в МОНИТОР (адрес 0000H)
        END     START
