; hello.asm — «Hello» для МОНИТОРА-F (полная конфигурация: модуль 1 + дисплейный
; модуль + ОЗУ 64 Кбайт).
;
; Программа выводит на экран две строки через подпрограмму МОНИТОРА-F F809H (вывод
; символа из регистра C, doc/27-monitor-f.md) и выходит в МОНИТОР-F по адресу тёплого
; старта F86CH — на экране снова приглашение «=>».
;
; Строки — в кодировке КОИ-7 ЮТ-88 (по умолчанию у ассемблера): латинские прописные
; как в ASCII, русские буквы — 60H–7EH.
;
; Конфигурация: full (программа в ОЗУ с 3000H).
; Сборка:  make asm F=examples/asm/hello.asm          (дамп examples/asm/hello.hex)
; Запуск:  make asm-run F=examples/asm/hello.asm      (конфигурация full — по F8xxH)
; На ЮТ-88: ввести коды директивой «M» МОНИТОРА-F с адреса 3000, пуск — G3000.

PUTCH   EQU     0F809H          ; МОНИТОР-F: вывод символа из C
WARM    EQU     0F86CH          ; МОНИТОР-F: тёплый старт (приглашение «=>»)
CR      EQU     0DH
LF      EQU     0AH

        ORG     3000H
START:  LXI     H,MSG           ; HL — адрес строки
NEXT:   MOV     A,M             ; очередной символ
        ORA     A               ; 0 — конец строки
        JZ      DONE
        MOV     C,A
        PUSH    H               ; HL сохраняем сами: не полагаемся на МОНИТОР
        CALL    PUTCH
        POP     H
        INX     H
        JMP     NEXT
DONE:   JMP     WARM            ; выход в МОНИТОР-F

MSG:    DB      CR,LF,'HELLO, WORLD!'
        DB      CR,LF,'ПРИВЕТ, ЮТ-88!',0
        END     START
