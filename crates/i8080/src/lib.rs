//! Эмулятор процессора КР580ВМ80А (советский аналог Intel 8080).
//!
//! Крейт не зависит ни от чего, кроме стандартной библиотеки, и ничего не знает о машине,
//! в которой работает процессор: память и порты ввода-вывода предоставляет трейт [`Bus`].
//!
//! - [`Cpu`] — регистры, флаги, выполнение всех 256 кодов команд с точным числом тактов,
//!   прерывания (INTE, задержка EI, приём кода команды по INTA), HLT;
//! - [`disasm`] — дизассемблер в мнемонике Intel (`MOV A,B`, `LXI H,1234H`, `JMP 0C000H`).

mod cpu;
mod disasm;

pub use cpu::{Cpu, HALT_STEP_CYCLES};
pub use disasm::{disasm, instruction_len};

/// Шина процессора: память (64 Кбайт) и порты ввода-вывода (256 портов).
pub trait Bus {
    /// Чтение байта памяти.
    fn read(&mut self, addr: u16) -> u8;
    /// Запись байта в память.
    fn write(&mut self, addr: u16, v: u8);
    /// Команда `IN port`.
    fn input(&mut self, port: u8) -> u8;
    /// Команда `OUT port`.
    fn output(&mut self, port: u8, v: u8);
}
