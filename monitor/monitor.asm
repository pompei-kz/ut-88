;==============================================================================
;  МОНИТОР ЮТ-88 (ПЗУ 0000H-03FFH), процессор КР580ВМ80А (Intel 8080)
;  Дизассемблировано по фотографиям дампа monitor-1.png / monitor-2.png
;
;  Оборудование:
;    9000H        - индикатор: 2 младших разряда (байт данных)
;    9001H-9002H  - индикатор: 4 старших разряда (адрес, L,H)
;    порт A0H     - клавиатура (0 = нет нажатия, 80H = клавиша "ШГ" (шаг назад))
;    порт A1H     - магнитофон (бит 0 - вход/выход)
;    C000H-C3FFH  - ОЗУ 1 Кб
;    RST 7        - прерывание от таймера 1 Гц (часы)
;
;  Рабочие ячейки ОЗУ:
;    C3EEH        - вершина стека (SP), там же параметр директивы замены адресов
;    C3F0H..C3FAH - параметры служебных подпрограмм перемещения/коррекции
;    C3FCH        - признак полярности сигнала магнитофона (00/FF)
;    C3FDH        - часы: секунды (BCD)
;    C3FEH        - часы: минуты  (BCD)
;    C3FFH        - часы: часы    (BCD)
;
;  Директивы (цифра с клавиатуры после индикации "11"):
;    0 - ввод (запись) в память с адреса      8 - контрольная сумма блока
;    1 - ввод в память с адреса C000H         9 - запись на магнитофон
;    2 - просмотр памяти с адреса C000H       A - чтение с магнитофона
;    3 - тест индикатора                      B - индикация часов
;    4 - тест ОЗУ C000H-C3FFH                 C - ввод в память (с запретом
;    5 - просмотр памяти с адреса                 прерываний, часы стоят)
;    6 - запуск программы с адреса C000H
;    7 - запуск программы с адреса
;
;  Дополнительные подпрограммы (запуск директивой 7 по адресу):
;    0200H - перемещение блока памяти
;    025FH - перемещение блока с коррекцией адресов
;    02E5H - коррекция адресов в блоке (под будущий адрес размещения)
;    0309H - замена адреса в 3-байтовых командах блока
;    035EH - вставка байта
;    0388H - удаление байта
;    03B2H - сравнение двух блоков памяти
;    03DDH - вывод на индикатор содержимого регистров (CALL 03DDH из программы)
;==============================================================================

DISP_D      EQU     9000H           ; индикатор данных
DISP_A      EQU     9001H           ; индикатор адреса
KBD         EQU     0A0H            ; порт клавиатуры
TAPE        EQU     0A1H            ; порт магнитофона
RAM         EQU     0C000H          ; начало ОЗУ
STACK       EQU     0C3EEH          ; вершина стека

V_START     EQU     0C3F0H          ; начальный адрес исходного блока
V_END       EQU     0C3F2H          ; конечный адрес исходного блока
V_NSTART    EQU     0C3F4H          ; начальный адрес обрабатываемого блока
V_NEND      EQU     0C3F6H          ; конечный адрес обрабатываемого блока
V_OFFS      EQU     0C3F8H          ; смещение (новый адрес - старый)
V_ADDR      EQU     0C3FAH          ; новый адрес / заменяемый адрес
V_ADDR2     EQU     0C3EEH          ; адрес-замена (директива 0309H)
TPOL        EQU     0C3FCH          ; полярность магнитофона
CLK_S       EQU     0C3FDH          ; секунды
CLK_M       EQU     0C3FEH          ; минуты
CLK_H       EQU     0C3FFH          ; часы

            ORG     0000H

;------------------------------------------------------------------------------
; RST 0 - холодный/горячий старт монитора
;------------------------------------------------------------------------------
START:      LXI     SP,STACK
            MVI     A,11H           ; приглашение "11" на индикаторе
            JMP     MONITOR

;------------------------------------------------------------------------------
; RST 1 - вывод байта A на магнитофон
;------------------------------------------------------------------------------
RST1:       JMP     TAPEOUT

; директива 5: просмотр памяти с введённого адреса
DIR5:       RST     6               ; ввод адреса в DE
            XCHG
            JMP     VIEW

;------------------------------------------------------------------------------
; RST 2 - ввод байта с клавиатуры (две 16-ричные цифры) в A,
;         с отображением на индикаторе данных
;------------------------------------------------------------------------------
RST2:       PUSH    D
            XRA     A
            MOV     D,A
            RST     4               ; первая цифра (старшая тетрада)
            RLC
            JMP     INBYTE2

;------------------------------------------------------------------------------
; RST 3 - пауза (~0.25-0.5 с), защита от дребезга / автоповтора клавиш
;------------------------------------------------------------------------------
RST3:       PUSH    H
            PUSH    PSW
            LXI     H,6650H
            JMP     DELAY

;------------------------------------------------------------------------------
; RST 4 - ожидание нажатия клавиши, код 0..F в A
;------------------------------------------------------------------------------
RST4:       RST     3
            JMP     GETKEY
            DB      00H

; директива 6: запуск программы с адреса C000H
DIR6:       JMP     RAM

;------------------------------------------------------------------------------
; RST 5 - вывод на индикатор: A - в разряды данных, HL - в разряды адреса
;------------------------------------------------------------------------------
RST5:       STA     DISP_D
            SHLD    DISP_A
            RET
            DB      00H

;------------------------------------------------------------------------------
; RST 6 - ввод 16-битного адреса с клавиатуры в DE (D - старший байт)
;------------------------------------------------------------------------------
RST6:       PUSH    PSW
            RST     2
            MOV     D,A
            RST     2
            MOV     E,A
            POP     PSW
            RET
            DB      00H

;------------------------------------------------------------------------------
; RST 7 - прерывание от таймера (часы)
;------------------------------------------------------------------------------
RST7:       JMP     CLOCK

;------------------------------------------------------------------------------
; Основной цикл монитора: показать A, принять номер директивы, перейти
;------------------------------------------------------------------------------
MONITOR:    EI
            STA     DISP_D
            RST     4               ; номер директивы 0..F
            ADI     DIRTAB          ; A = младший байт адреса в таблице
            MVI     H,00H
            MOV     L,A
            MOV     L,M             ; L = младший байт адреса обработчика
            PCHL                    ; все обработчики - в 0000H..00FFH

; продолжение RST 2: вторая цифра
INBYTE2:    RLC
            RLC
            RLC                     ; A = цифра * 16
            ORA     D
            MOV     D,A
            STA     DISP_D
            RST     4               ; вторая цифра (младшая тетрада)
            ORA     D
            STA     DISP_D
            POP     D
            RET

; продолжение RST 3: цикл задержки
DELAY:      DCX     H
            MOV     A,L
            ORA     H
            JNZ     DELAY
            POP     PSW
            POP     H
            RET

; продолжение RST 4: опрос клавиатуры
GETKEY:     IN      KBD
            ADI     00H             ; установить флаги
            JZ      GETKEY          ; клавиша не нажата - ждать
            CPI     80H
            JZ      KEYBACK         ; клавиша "ШГ" - шаг назад
            ANI     0FH
            RET

; клавиша "ШГ": вернуться на предыдущий адрес и перейти в режим ввода
; (ИСПРАВЛЕНО: в оригинальном дампе здесь DCX SP / DCX SP (3B 3B),
;  заменено на INX SP / INX SP (33 33) - снять адрес возврата из стека)
KEYBACK:    DCX     H
            INX     SP
            INX     SP

;------------------------------------------------------------------------------
; Ввод в память с адреса HL (бесконечный цикл, выход - RESET)
;------------------------------------------------------------------------------
WRMEM:      XRA     A
            RST     5               ; показать адрес HL и 00
            RST     2               ; ввести байт
            MOV     M,A             ; записать в память
            RST     3
            INX     H
            JMP     WRMEM

; директива 2: просмотр памяти с адреса C000H
DIR2:       LXI     H,RAM

; просмотр памяти с адреса HL: каждая клавиша - следующий адрес
VIEW:       RST     4
            MOV     A,M
            RST     5
            INX     H
            JMP     VIEW

; директива 7: запуск программы с введённого адреса
DIR7:       RST     6
            XCHG
            XRA     A
            RST     5
            RST     3
            PCHL

; директива 1: ввод в память с адреса C000H
DIR1:       LXI     H,RAM
            JMP     WRMEM

; директива C: ввод в память с запретом прерываний
DIRC:       DI
; директива 0: ввод в память с введённого адреса
DIR0:       RST     6
            XCHG
            JMP     WRMEM

;------------------------------------------------------------------------------
; Директива 3: тест индикатора - на всех разрядах 00,11,22,...,FF
;------------------------------------------------------------------------------
DIR3:       XRA     A
DIR3L:      MOV     H,A
            MOV     L,A
            RST     5
            RST     3
            ADI     11H
            CPI     10H             ; после FF+11 = 10 - конец
            JNZ     DIR3L
            RST     0

;------------------------------------------------------------------------------
; Директива 4: тест ОЗУ C000H-C3FFH (запись 00 и FF с проверкой).
; При ошибке показывает адрес и прочитанный байт, клавиша - продолжить
;------------------------------------------------------------------------------
DIR4:       LXI     H,RAM
MTEST:      XRA     A
            MOV     M,A
            MOV     A,M
            ORA     A
            JNZ     MTERR           ; не записался 00
            DCR     A
            MOV     M,A
            MOV     A,M
            INR     A
            JNZ     MTERR           ; не записался FF
            INX     H
            MOV     A,H
            ANI     04H             ; дошли до C400H?
            JZ      MTEST
MTERR:      MOV     A,M
            RST     5
            RST     4
            JMP     MTEST

;------------------------------------------------------------------------------
; Обработчик прерывания таймера: секунды/минуты/часы в BCD
;------------------------------------------------------------------------------
CLOCK:      DI
            PUSH    PSW
            PUSH    B
            PUSH    D
            PUSH    H
            LXI     H,CLKLIM
            LXI     D,CLK_S
            MVI     B,03H
CLKL:       LDAX    D
            INR     A
            DAA
            STAX    D
            CMP     M               ; достигнут предел?
            JNZ     CLKX
            XRA     A               ; обнулить и перенести в старший
            STAX    D
            INX     H
            INX     D
            DCR     B
            JNZ     CLKL
CLKX:       POP     H
            POP     D
            POP     B
            POP     PSW
            EI
            RET

CLKLIM:     DB      60H,60H,24H     ; пределы: секунды, минуты, часы

DIR9:       JMP     TWRITE          ; директива 9: запись на магнитофон
DIRA:       JMP     TREAD           ; директива A: чтение с магнитофона
DIR8:       JMP     CHKSUM          ; директива 8: контрольная сумма
DIRB:       JMP     SHOWCLK         ; директива B: индикация часов

; Таблица директив: младшие байты адресов обработчиков (страница 00xxH)
DIRTAB:     DB      DIR0            ; 0 - 91H
            DB      DIR1            ; 1 - 8AH
            DB      DIR2            ; 2 - 7AH
            DB      DIR3            ; 3 - 96H
            DB      DIR4            ; 4 - A3H
            DB      DIR5            ; 5 - 0BH
            DB      DIR6            ; 6 - 25H
            DB      DIR7            ; 7 - 84H
            DB      DIR8            ; 8 - EDH
            DB      DIR9            ; 9 - E7H
            DB      DIRA            ; A - EAH
            DB      DIRB            ; B - F0H
            DB      DIRC            ; C - 90H

;------------------------------------------------------------------------------
; Вывод байта A на магнитофон (фазовое кодирование, старшим битом вперёд)
;------------------------------------------------------------------------------
TAPEOUT:    PUSH    B
            PUSH    D
            PUSH    PSW
            MOV     D,A
            MVI     C,08H
TOUTL:      MOV     A,D
            RLC
            MOV     D,A
            MVI     A,01H
            XRA     D
            OUT     TAPE            ; первая половина бита - инверсия
            CALL    TDELAY
            MVI     A,00H
            XRA     D
            OUT     TAPE            ; вторая половина бита - прямой
            CALL    TDELAY
            DCR     C
            JNZ     TOUTL
            POP     PSW
            POP     D
            POP     B
            RET

TDELAY:     MVI     B,1EH           ; задержка полупериода записи
TDL:        DCR     B
            JNZ     TDL
            RET

;------------------------------------------------------------------------------
; Ввод байта с магнитофона.
;   A = FFH - с поиском синхробайта E6H (определяется и полярность),
;   A = 08H - чтение очередного байта без поиска.
;   Результат в A.
;------------------------------------------------------------------------------
TAPEIN:     PUSH    B
            PUSH    D
            MVI     C,00H
            MOV     D,A
            IN      TAPE
            MOV     E,A
TINL:       MOV     A,C
            ANI     7FH
            RLC
            MOV     C,A
TINW:       IN      TAPE
            CMP     E
            JZ      TINW            ; ждать перепада
            ANI     01H
            ORA     C
            MOV     C,A
            CALL    TIDELAY
            IN      TAPE
            MOV     E,A
            MOV     A,D
            ORA     A
            JP      TINCNT          ; поиск синхробайта не нужен
            MOV     A,C
            CPI     0E6H
            JNZ     TIN19
            XRA     A               ; прямая полярность
            STA     TPOL
            JMP     TINSYN
TIN19:      CPI     19H             ; E6H инвертированный
            JNZ     TINL
            MVI     A,0FFH          ; обратная полярность
            STA     TPOL
TINSYN:     MVI     D,09H
TINCNT:     DCR     D
            JNZ     TINL
            LDA     TPOL
            XRA     C               ; учесть полярность
            POP     D
            POP     B
            RET

TIDELAY:    MVI     B,2DH           ; задержка 3/4 периода при чтении
TIDL:       DCR     B
            JNZ     TIDL
            RET

;------------------------------------------------------------------------------
; Директива 8: контрольная сумма блока (ввод: начало, конец).
; Сумма (16 бит) - на индикаторе адреса.
;------------------------------------------------------------------------------
CHKSUM:     PUSH    B
            PUSH    D
            PUSH    H
            PUSH    PSW
            RST     6
            MOV     B,D
            MOV     C,E             ; BC = начало
            RST     6               ; DE = конец
CHKSUM1:    MVI     L,00H
            MOV     H,L
CHKL:       LDAX    B
            PUSH    D
            MOV     E,A
            MVI     D,00H
            DAD     D
            POP     D
            CALL    CMPBD
            INX     B
            JNZ     CHKL
            RST     5
            POP     PSW
            POP     H
            POP     D
            POP     B
            RST     0

; сравнение DE и BC (Z=1 если равны)
CMPBD:      MOV     A,D
            CMP     B
            RNZ
            MOV     A,E
            CMP     C
            RET

;------------------------------------------------------------------------------
; Директива 9: запись блока на магнитофон (ввод: начало, конец).
; Формат: 256 x 00H, E6H, начало(H,L), конец(H,L), данные.
; После записи показывает контрольную сумму.
;------------------------------------------------------------------------------
TWRITE:     PUSH    B
            PUSH    D
            PUSH    H
            PUSH    PSW
            RST     6
            MOV     B,D
            MOV     C,E             ; BC = начало
            RST     6               ; DE = конец
            PUSH    B
            XRA     A
            MOV     L,A
TWPIL:      RST     1               ; пилот-тон: 256 нулей
            INR     L
            JNZ     TWPIL
            MVI     A,0E6H          ; синхробайт
            RST     1
            MOV     A,B
            RST     1
            MOV     A,C
            RST     1
            MOV     A,D
            RST     1
            MOV     A,E
            RST     1
TWDAT:      LDAX    B
            RST     1
            CALL    CMPBD
            INX     B
            JNZ     TWDAT
            POP     B
            JMP     CHKSUM1

;------------------------------------------------------------------------------
; Директива A: чтение блока с магнитофона (ввод: смещение адреса загрузки).
; После чтения показывает контрольную сумму.
;------------------------------------------------------------------------------
TREAD:      PUSH    B
            PUSH    D
            PUSH    H
            PUSH    PSW
            RST     6               ; DE = смещение
            MVI     A,0FFH          ; поиск синхробайта
            CALL    TAPEIN
            MOV     H,A
            CALL    TIN8
            MOV     L,A
            DAD     D
            MOV     B,H
            MOV     C,L             ; BC = начало + смещение
            PUSH    B
            CALL    TIN8
            MOV     H,A
            CALL    TIN8
            MOV     L,A
            DAD     D
            XCHG                    ; DE = конец + смещение
TRDAT:      CALL    TIN8
            STAX    B
            CALL    CMPBD
            INX     B
            JNZ     TRDAT
            POP     B
            JMP     CHKSUM1

TIN8:       MVI     A,08H           ; чтение байта без поиска синхро
            CALL    TAPEIN
            RET
            DB      00H

;------------------------------------------------------------------------------
; Директива B: индикация часов (ЧЧ ММ СС), выход - RESET
;------------------------------------------------------------------------------
SHOWCLK:    LHLD    CLK_M           ; L = минуты, H = часы
            LDA     CLK_S
            RST     5
            RST     3
            JMP     SHOWCLK

;------------------------------------------------------------------------------
; 0200H: перемещение блока памяти (ввод: начало, конец, адрес назначения).
; Корректно при перекрытии областей.
;------------------------------------------------------------------------------
MOVE:       CALL    MVPARM
            JC      MOVEUP
            CALL    COPYDN          ; назначение выше - копируем с конца
            RST     0
MOVEUP:     CALL    COPYUP          ; назначение ниже - копируем с начала
            RST     0

; копирование (DE)->(HL) с уменьшением адресов, пока DE <> BC (включительно)
COPYDN:     LDAX    D
            MOV     M,A
            CALL    CMPBD
            DCX     D
            DCX     H
            JNZ     COPYDN
            RET

; копирование (BC)->(HL) с увеличением адресов, пока BC <> DE (включительно)
COPYUP:     LDAX    B
            MOV     M,A
            CALL    CMPBD
            INX     B
            INX     H
            JNZ     COPYUP
            RET

; ввод параметров перемещения и подготовка регистров:
;   V_START, V_END - исходный блок, V_NSTART, V_NEND - новый блок,
;   V_OFFS - смещение; BC = начало, DE = конец;
;   CY=1: HL = новое начало (назначение ниже исходного),
;   CY=0: HL = новый конец
MVPARM:     RST     6
            PUSH    D
            RST     6
            XCHG
            SHLD    V_END
            POP     H
            SHLD    V_START
            RST     6
            XCHG
            SHLD    V_NSTART
            MOV     A,L
            SUB     E
            MOV     L,A
            MOV     A,H
            SBB     D
            MOV     H,A
            SHLD    V_OFFS          ; смещение = назначение - начало
            MOV     C,L
            MOV     B,H
            LHLD    V_END
            PUSH    H
            DAD     B
            SHLD    V_NEND          ; новый конец = конец + смещение
            LHLD    V_START
            MOV     C,L
            MOV     B,H
            POP     D
            LHLD    V_NSTART
            MOV     A,L
            SUB     C
            MOV     A,H
            SBB     B
            RC
            LHLD    V_NEND
            RET

; сравнение HL и DE (Z=1 если равны)
CMPHD:      MOV     A,H
            CMP     D
            RNZ
            MOV     A,L
            CMP     E
            RET

;------------------------------------------------------------------------------
; 025FH: перемещение блока с коррекцией адресов
;------------------------------------------------------------------------------
MOVEREL:    CALL    MVPARM
            CALL    RELOC
            RST     0

;------------------------------------------------------------------------------
; Коррекция адресов в блоке V_NSTART..V_NEND: в 3-байтовых командах
; операнд, попадающий в V_START..V_END, увеличивается на V_OFFS.
;------------------------------------------------------------------------------
RELOC:      LHLD    V_NSTART
RELL:       MOV     D,M             ; D = код команды
            PUSH    H
            CALL    CMDLEN          ; B = длина команды
            MOV     H,B
            XTHL                    ; в стек - длина, HL - адрес команды
            MOV     A,B
            CPI     03H
            JNZ     RELSKIP
            INX     H
            MOV     C,M
            INX     H
            MOV     B,M             ; BC = операнд
            DCX     H
            PUSH    H
            LHLD    V_START
            MOV     A,C
            SUB     L
            MOV     A,B
            SBB     H
            JC      RELNO           ; операнд < начала
            LHLD    V_END
            MOV     A,L
            SUB     C
            MOV     A,H
            SBB     B
            JC      RELNO           ; операнд > конца
            LHLD    V_OFFS
            MOV     A,L
            ADD     C
            MOV     E,A
            MOV     A,H
            ADC     B
            MOV     D,A             ; DE = операнд + смещение
            POP     H
            MOV     M,E
            INX     H
            MOV     M,D
            INX     H               ; HL - на следующую команду
            INX     SP
            INX     SP              ; убрать длину из стека
            JMP     RELNXT
RELNO:      POP     H
            DCX     H
RELSKIP:    POP     B               ; B = длина
RELADV:     INX     H
            DCR     B
            JNZ     RELADV
RELNXT:     MOV     E,L
            MOV     D,H
            LHLD    V_NEND
            INX     H
            CALL    CMPHD           ; дошли до конца блока?
            XCHG
            JNZ     RELL
            RET

;------------------------------------------------------------------------------
; Определение длины команды по коду в D. Результат: B = 1, 2 или 3.
;------------------------------------------------------------------------------
CMDLEN:     LXI     B,0306H         ; B = 3 (длина), C = 6 (пар в группе)
            LXI     H,LENTAB
CLL:        MOV     A,D
            ANA     M               ; маска
            INX     H
            CMP     M               ; образец
            RZ
            INX     H
            DCR     C
            JNZ     CLL
            MVI     C,03H           ; 3 пары для 2-байтовых команд
            DCR     B
            MOV     A,B
            CPI     01H
            JNZ     CLL
            RET

; таблица (маска, образец)
LENTAB:     DB      0FFH,0CDH       ; CALL
            DB      0C7H,0C4H       ; Cxx
            DB      0FFH,0C3H       ; JMP
            DB      0C7H,0C2H       ; Jxx
            DB      0E7H,022H       ; SHLD/LHLD/STA/LDA
            DB      0CFH,001H       ; LXI
            DB      0C7H,006H       ; MVI
            DB      0C7H,0C6H       ; ADI..CPI
            DB      0F7H,0D3H       ; OUT/IN

;------------------------------------------------------------------------------
; 02E5H: коррекция адресов в блоке на месте под будущий адрес
;        (ввод: начало, конец, адрес будущего размещения)
;------------------------------------------------------------------------------
ADJUST:     RST     6
            XCHG
            SHLD    V_START
            SHLD    V_NSTART
            PUSH    H
            RST     6
            XCHG
            SHLD    V_END
            SHLD    V_NEND
            RST     6
            XCHG
            SHLD    V_ADDR
            POP     D
            MOV     A,L
            SUB     E
            MOV     L,A
            MOV     A,H
            SBB     D
            MOV     H,A
            SHLD    V_OFFS
            CALL    RELOC
            RST     0

;------------------------------------------------------------------------------
; 0309H: замена адреса в 3-байтовых командах блока
;        (ввод: начало, конец, старый адрес, новый адрес)
;------------------------------------------------------------------------------
REPADR:     RST     6
            PUSH    D
            RST     6
            XCHG
            SHLD    V_END
            RST     6
            XCHG
            SHLD    V_ADDR          ; что искать
            RST     6
            XCHG
            SHLD    V_ADDR2         ; на что заменить
            POP     H
            SHLD    V_START
RPL:        MOV     D,M
            PUSH    H
            CALL    CMDLEN
            MOV     H,B
            XTHL
            MOV     A,B
            CPI     03H
            JNZ     RPSKIP
            INX     H
            MOV     E,M
            INX     H
            MOV     D,M             ; DE = операнд
            DCX     H
            PUSH    H
            LHLD    V_ADDR
            CALL    CMPHD
            JNZ     RPNO
            LHLD    V_ADDR2
            XCHG
            POP     H
            MOV     M,E
            INX     H
            MOV     M,D
            INX     H
            INX     SP
            INX     SP
            JMP     RPNXT
RPNO:       POP     H
            DCX     H
RPSKIP:     POP     B
RPADV:      INX     H
            DCR     B
            JNZ     RPADV
RPNXT:      MOV     E,L
            MOV     D,H
            LHLD    V_END
            INX     H
            CALL    CMPHD
            XCHG
            JNZ     RPL
            RST     0

;------------------------------------------------------------------------------
; 035EH: вставка байта (ввод: адрес вставки, конец программы, затем байт).
; Блок сдвигается на 1 вверх, адреса корректируются.
;------------------------------------------------------------------------------
INSBYTE:    RST     6
            XCHG
            SHLD    V_START
            MOV     C,L
            MOV     B,H             ; BC = адрес вставки
            RST     6
            MOV     L,E
            MOV     H,D
            SHLD    V_END
            INX     H
            SHLD    V_NEND
            CALL    COPYDN          ; сдвиг блока вверх на 1
            XRA     A
            MOV     M,A
            PUSH    H
            INX     H
            SHLD    V_NSTART
            LXI     H,0001H
            SHLD    V_OFFS
            CALL    RELOC
            POP     H
            MOV     A,M
            RST     5
            RST     2               ; ввод вставляемого байта
            MOV     M,A
            RST     0

;------------------------------------------------------------------------------
; 0388H: удаление байта (ввод: адрес удаляемого байта, конец программы).
; Блок сдвигается на 1 вниз, адреса корректируются, затем просмотр памяти.
;------------------------------------------------------------------------------
DELBYTE:    RST     6
            XCHG
            SHLD    V_START
            SHLD    V_NSTART
            MOV     C,L
            MOV     B,H
            PUSH    H
            RST     6
            MOV     L,E
            MOV     H,D
            SHLD    V_END
            POP     H
            PUSH    B
            INX     B
            CALL    COPYUP          ; сдвиг блока вниз на 1
            XRA     A
            MOV     M,A
            DCX     H
            SHLD    V_NEND
            LXI     H,0FFFFH        ; смещение -1
            SHLD    V_OFFS
            CALL    RELOC
            POP     H
            JMP     VIEW

;------------------------------------------------------------------------------
; 03B2H: сравнение блоков (ввод: начало 1, конец 1, начало 2).
; При несовпадении показывает адрес и байт блока 2, ждёт ввода нового
; значения. По окончании - "1111 11" на индикаторе.
;------------------------------------------------------------------------------
COMPARE:    RST     6
            MOV     C,E
            MOV     B,D             ; BC = начало 1
            RST     6
            PUSH    D               ; конец 1
            RST     6
            XCHG                    ; HL = начало 2
            POP     D
CMPL:       LDAX    B
            CMP     M
            JNZ     CMPDIF
            MOV     A,C
            CMP     E
            JNZ     CMPNXT
            MOV     A,B
            CMP     D
            JNZ     CMPNXT
            MVI     A,11H
            MOV     L,A
            MOV     H,A
            RST     5
            RST     0
CMPNXT:     INX     B
            INX     H
            JMP     CMPL
CMPDIF:     PUSH    PSW
            MOV     A,M
            RST     5
            RST     2
            MOV     M,A
            POP     PSW
            JMP     CMPL

;------------------------------------------------------------------------------
; 03DDH: индикация регистров (вызывается из программы CALL 03DDH).
; Последовательно по нажатию клавиши: HL и (HL); "AF" и A,F;
; "BC" и BC; "DE" и DE. Все регистры сохраняются.
;------------------------------------------------------------------------------
REGS:       PUSH    B
            PUSH    D
            PUSH    H
            PUSH    PSW
            MOV     A,M
            RST     5               ; HL, (HL)
            RST     4
            XTHL                    ; HL = PSW
            MVI     A,0AFH
            RST     5               ; A,F  "AF"
            RST     4
            XTHL
            MOV     L,C
            MOV     H,B
            MVI     A,0BCH
            RST     5               ; BC   "BC"
            RST     4
            XCHG
            MVI     A,0DEH
            RST     5               ; DE   "DE"
            RST     4
            POP     PSW
            POP     H
            POP     D
            POP     B
            RET

            DB      0FFH,0FFH,0FFH,0FFH,0FFH,0FFH

            END
